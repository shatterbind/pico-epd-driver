#!/usr/bin/env python3
"""
convert_image.py

Utility to convert any image (PNG, JPG, BMP) into a 2-bit packed C array for the
Pico E-Paper Driver (pico-epd-driver).

Color mapping:
    BLACK  = 0 (00b)
    WHITE  = 1 (01b)
    YELLOW = 2 (10b)
    RED    = 3 (11b)

Bit packing (MSB first, 4 pixels per byte):
    Byte = (p0 << 6) | (p1 << 4) | (p2 << 2) | p3

Usage:
    py scripts/convert_image.py input.png [output.h] [--width 64] [--height 64] [--name rpi_logo]
"""

import argparse
import os
import sys
from PIL import Image

PALETTE = {
    0: (0, 0, 0),       # BLACK
    1: (255, 255, 255), # WHITE
    2: (255, 200, 0),   # YELLOW
    3: (220, 0, 0),     # RED
}

def color_distance_sq(c1, c2):
    # Perceptually weighted color distance
    r1, g1, b1 = c1[:3]
    r2, g2, b2 = c2[:3]
    return 0.299 * (r1 - r2) ** 2 + 0.587 * (g1 - g2) ** 2 + 0.114 * (b1 - b2) ** 2

def quantize_pixel(rgb):
    r, g, b = rgb[:3]
    # Check for near white / black thresholds first
    if r > 230 and g > 230 and b > 230:
        return 1
    if r < 40 and g < 40 and b < 40:
        return 0
    best_c = 1
    best_d = float('inf')
    for code, target_rgb in PALETTE.items():
        d = color_distance_sq((r, g, b), target_rgb)
        if d < best_d:
            best_d = d
            best_c = code
    return best_c

def convert_image(input_path, output_path, width, height, var_name):
    img = Image.open(input_path).convert('RGB')
    if img.size != (width, height):
        img = img.resize((width, height), Image.Resampling.LANCZOS)

    # 2bpp packed bytes: 4 pixels per byte
    bytes_per_row = (width * 2 + 7) // 8
    total_bytes = bytes_per_row * height

    header_guard = f"{var_name.upper()}_H"
    lines = [
        f"// Auto-generated by convert_image.py from {os.path.basename(input_path)}",
        f"// Dimensions: {width}x{height}, 2 bits per pixel, {total_bytes} bytes",
        f"// Color palette: BLACK=0 (00b), WHITE=1 (01b), YELLOW=2 (10b), RED=3 (11b)",
        f"#ifndef {header_guard}",
        f"#define {header_guard}",
        f"",
        f"#include <stdint.h>",
        f"",
        f"#define {var_name.upper()}_WIDTH  {width}",
        f"#define {var_name.upper()}_HEIGHT {height}",
        f"",
        f"static const uint8_t {var_name}_{width}x{height}[{total_bytes}] = {{"
    ]

    for y in range(height):
        row_bytes = []
        for x in range(0, width, 4):
            b = 0
            for shift_idx, px_offset in enumerate(range(4)):
                px = x + px_offset
                if px < width:
                    c = quantize_pixel(img.getpixel((px, y)))
                else:
                    c = 1 # White padding
                shift = (3 - shift_idx) * 2
                b |= (c & 0x03) << shift
            row_bytes.append(f"0x{b:02X}")
        lines.append(f"    {', '.join(row_bytes)}, // Row {y}")

    lines.extend([
        f"}};",
        f"",
        f"#endif // {header_guard}",
        f""
    ])

    with open(output_path, "w") as f:
        f.write("\n".join(lines))

    print(f"Generated {output_path} ({width}x{height}, {total_bytes} bytes)")

def main():
    parser = argparse.ArgumentParser(description="Convert an image into a packed 2-bit C array.")
    parser.add_argument("input", help="Input image file (PNG, JPG, BMP)")
    parser.add_argument("output", nargs="?", default=None, help="Output C header file (.h)")
    parser.add_argument("--width", type=int, default=64, help="Target width (default: 64)")
    parser.add_argument("--height", type=int, default=64, help="Target height (default: 64)")
    parser.add_argument("--name", default=None, help="C variable name prefix")

    args = parser.parse_args()

    base_name = os.path.splitext(os.path.basename(args.input))[0]
    var_name = args.name if args.name else base_name
    output_path = args.output if args.output else f"{var_name}.h"

    convert_image(args.input, output_path, args.width, args.height, var_name)

if __name__ == "__main__":
    main()
